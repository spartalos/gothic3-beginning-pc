package gothic3.buildtools;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.ArrayList;
import java.util.List;

/**
 * Converts the game's AMR-NB sound effects to 22050 Hz mono s16 WAV with ffmpeg (the JDK cannot decode AMR) and writes
 * audio/index.properties (sha1 of the original AMR bytes = wav name), which the MIDP shim uses at run time.
 * ffmpeg is looked up in this order: -Dg3.ffmpeg=(file or dir), the minimal ffmpeg bundled with the app (an {@code ffmpeg/} directory next
 * to the app's jar, see scripts/ffmpeg/build-minimal-ffmpeg.sh), then PATH. The OpenCORE decoder (libopencore_amrnb) is used when present
 * because ffmpeg's native decoder fails on the game's 6.7 kbps and SID frames (the bundled build contains only OpenCORE).
 */
final class AmrConverter {
    private AmrConverter() {}

    /** @return false when ffmpeg is missing and {@code required} is false (no files written); otherwise true. */
    static boolean convert(List<Path> amrs, Path outDir, boolean required) throws Exception {
        List<String> dec = new ArrayList<>();
        String ffmpeg = findFfmpeg();
        try {
            if (ffmpeg == null) throw new IOException("no ffmpeg");
            String decoders = capture(ffmpeg, "-hide_banner", "-decoders");
            if (decoders.contains("libopencore_amrnb")) { dec.add("-c:a"); dec.add("libopencore_amrnb"); }
        } catch (IOException e) {
            if (!required) { System.err.println("[audio] ffmpeg not found: the sound effects are skipped"); return false; }
            throw new GamePipeline.Failure("ffmpeg not found (bundled copy, -Dg3.ffmpeg or PATH). It is needed to convert the game's .amr sound effects "
                + "to WAV (install ffmpeg, preferably built with libopencore-amrnb).");
        }
        Files.createDirectories(outDir);
        StringBuilder idx = new StringBuilder("# Generated by gradle setupGame (buildtools AmrConverter). key = sha1 of original .amr bytes, value = converted WAV.\n");
        for (Path amr : amrs) {
            String name = amr.getFileName().toString().replaceAll("\\.amr$", "");
            Path wav = outDir.resolve(name + ".wav");
            List<String> cmd = new ArrayList<>(List.of(ffmpeg, "-v", "error", "-y"));
            cmd.addAll(dec);
            cmd.addAll(List.of("-i", amr.toString(), "-ar", "22050", "-ac", "1", "-c:a", "pcm_s16le", wav.toString()));
            Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
            ByteArrayOutputStream log = new ByteArrayOutputStream();
            p.getInputStream().transferTo(log);
            if (p.waitFor() != 0 || !Files.exists(wav))
                throw new GamePipeline.Failure("ffmpeg failed on " + amr + ":\n" + log.toString(StandardCharsets.UTF_8));
            if (dec.isEmpty()) {   // native decoder fallback: accept it only if it decoded the whole file (it truncates 6.7 kbps / SID streams)
                long want = amrFrames(amr) * 160L * 22050 / 8000 * 2, got = Files.size(wav) - 44;
                if (got < want * 0.98) {
                    Files.deleteIfExists(wav);
                    String msg = "this ffmpeg has no libopencore_amrnb and its native AMR-NB decoder truncated " + amr.getFileName()
                        + " (" + got + " of " + want + " PCM bytes); use the bundled ffmpeg or one built with libopencore-amrnb";
                    if (!required) { System.err.println("[audio] " + msg + ": the sound effects are skipped"); return false; }
                    throw new GamePipeline.Failure(msg);
                }
            }
            idx.append(GamePipeline.sha1(amr)).append("=audio/").append(name).append(".wav\n");
        }
        Files.writeString(outDir.resolve("index.properties"), idx.toString());
        System.out.println("converted " + amrs.size() + " AMR files to WAV");
        return true;
    }

    /** Number of 20 ms frames in an AMR-NB storage file ("#!AMR\n" + TOC byte and payload per frame). */
    static int amrFrames(Path amr) throws IOException {
        byte[] d = Files.readAllBytes(amr);
        int[] size = {13, 14, 16, 18, 20, 21, 27, 32, 6, 1, 1, 1, 1, 1, 1, 1};   // TOC byte + payload per frame type
        int n = 0;
        for (int i = 6; i < d.length; i += size[(d[i] >> 3) & 15]) n++;
        return n;
    }

    private static boolean works(String exe) {
        try { return capture(exe, "-version").startsWith("ffmpeg version"); } catch (Exception e) { return false; }
    }

    /** @return the ffmpeg executable to run (a path, or the bare name "ffmpeg" for PATH), or null when none works. */
    static String findFfmpeg() {
        String exeName = System.getProperty("os.name", "").toLowerCase().contains("win") ? "ffmpeg.exe" : "ffmpeg";
        List<Path> cands = new ArrayList<>();
        String prop = System.getProperty("g3.ffmpeg");
        boolean hasProp = prop != null && !prop.isBlank();
        if (hasProp) {
            Path p = Paths.get(prop);
            cands.add(Files.isDirectory(p) ? p.resolve(exeName) : p);
        }
        try {
            Path loc = Paths.get(AmrConverter.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            // the app's jar: <app>/gothic3.jar, the bundled ffmpeg in <app>/ffmpeg/ (not for build-output class directories)
            if (Files.isRegularFile(loc)) cands.add(loc.getParent().resolve("ffmpeg").resolve(exeName));
        } catch (Exception ignored) { }
        for (Path c : cands) {
            if (!Files.isRegularFile(c)) continue;
            if (!Files.isExecutable(c)) c.toFile().setExecutable(true);
            if (works(c.toString())) { System.err.println("[audio] using ffmpeg " + c); return c.toString(); }
            System.err.println("[audio] ignoring unusable ffmpeg " + c);
        }
        if (hasProp) System.err.println("[audio] -Dg3.ffmpeg=" + prop + " not usable, trying PATH");
        return works("ffmpeg") ? "ffmpeg" : null;
    }

    static String capture(String... cmd) throws Exception {
        Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
        ByteArrayOutputStream o = new ByteArrayOutputStream();
        p.getInputStream().transferTo(o);
        p.waitFor();
        return o.toString(StandardCharsets.UTF_8);
    }
}
