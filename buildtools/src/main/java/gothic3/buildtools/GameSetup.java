package gothic3.buildtools;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.security.MessageDigest;
import java.util.*;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.jar.JarOutputStream;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import gothic3.buildtools.GamePipeline.Failure;
import static gothic3.buildtools.GamePipeline.*;

/**
 * "Bring your own jar" generator. Subcommands:
 * <pre>
 *   setup        verify jar -> remap -> decompile -> verify decompile hashes -> apply patches -> extract resources
 *   makepatches  regenerate game-patches/ from the (edited) generated sources
 *   record       (maintainers) write game-patches/decompile.sha256 from game/gen/pristine
 * </pre>
 * Options: --root DIR (repo root), --jar FILE, --force.
 */
public final class GameSetup {
    static Path root;
    static Path gen;        // game/gen
    static Path patches;    // game-patches
    static boolean force;
    static Path jar;
    static GamePipeline pl;
    static final Properties cfg = new Properties();

    public static void main(String[] args) throws Exception {
        String cmd = args.length > 0 ? args[0] : "";
        for (int i = 1; i < args.length; i++) {
            switch (args[i]) {
                case "--root": root = Paths.get(args[++i]).toAbsolutePath().normalize(); break;
                case "--jar": jar = Paths.get(args[++i]).toAbsolutePath().normalize(); break;
                case "--force": force = true; break;
                default: throw new IllegalArgumentException("unknown option " + args[i]);
            }
        }
        if (root == null) root = Paths.get("").toAbsolutePath();
        gen = root.resolve("game/gen");
        patches = root.resolve("game-patches");
        pl = new GamePipeline(root);
        cfg.putAll(pl.cfg);
        try {
            switch (cmd) {
                case "setup": setup(); break;
                case "makepatches": makePatches(); break;
                case "record": record(); break;
                default: throw new IllegalArgumentException("usage: setup|makepatches|record");
            }
        } catch (Failure e) {
            System.err.println("\nFAILED: " + e.getMessage());
            System.exit(1);
        }
    }

    
    // ------------------------------------------------------------------------------------------------ setup

    static void setup() throws Exception {
        if (jar == null) jar = root.resolve("original/" + cfg.getProperty("jar.name"));
        if (!Files.isRegularFile(jar))
            throw new Failure("game jar not found: " + jar + "\n  pass -PgameJar=<path to " + cfg.getProperty("jar.name") + ">");
        JarCheck.Result jr = JarCheck.inspect(jar, cfg);
        if (jr.kind != JarCheck.Kind.OK) throw new Failure("unsupported game jar " + jar + "\n" + jr.message());
        String sha = jr.sha;
        Path remapper = pl.tool("tiny-remapper");
        Path vineflower = pl.tool("vineflower");

        String inputs = inputsHash(sha, remapper, vineflower);
        Path stamp = gen.resolve(".stamp");
        if (Files.exists(stamp) && !force) {
            Properties st = new Properties();
            try (InputStream in = Files.newInputStream(stamp)) { st.load(in); }
            boolean sameInputs = inputs.equals(st.getProperty("inputs"));
            boolean intact = treeHash().equals(st.getProperty("tree"));
            if (sameInputs && intact) { System.out.println("setupGame: up to date"); return; }
            if (sameInputs) {
                System.out.println("setupGame: generated sources have local edits - keeping them "
                    + "(run makePatches to save them, or setupGame -Pforce to discard)");
                return;
            }
            if (!intact)
                throw new Failure("game/gen has local edits AND the inputs (jar/patches/tools/mapping) changed.\n"
                    + "  Run `./gradlew makePatches` first to save your edits, or `./gradlew setupGame -Pforce` to discard them.");
        }

        GamePipeline.Result res = pl.generate(jar, gen, true, GamePipeline.Audio.REQUIRED,
            (st, d) -> System.out.println("[" + st + "] " + d));
        System.out.println("applied " + res.patchFiles + " patch files");
        writeStamp(inputs);
        System.out.println("setupGame: generated " + gen);
    }

    static void writeStamp(String inputs) throws Exception {
        Properties st = new Properties();
        st.setProperty("inputs", inputs);
        st.setProperty("tree", treeHash());
        try (var out = Files.newOutputStream(gen.resolve(".stamp"))) { st.store(out, "generated by GameSetup; do not edit"); }
    }

    /** Hash over everything that determines the generated tree. */
    static String inputsHash(String jarSha, Path remapper, Path vineflower) throws Exception {
        MessageDigest md = MessageDigest.getInstance("SHA-256");
        md.update(("jar=" + jarSha + "\n").getBytes(StandardCharsets.UTF_8));
        md.update(("tools=" + sha256(remapper) + sha256(vineflower) + "\n").getBytes(StandardCharsets.UTF_8));
        for (Path dir : new Path[] {root.resolve("docs/mapping"), patches}) {
            hashTree(md, dir);
        }
        return hex(md.digest());
    }

    /** Hash of generated sources (what a developer edits). Resources are not hand-edited. */
    static String treeHash() throws Exception {
        MessageDigest md = MessageDigest.getInstance("SHA-256");
        Path src = gen.resolve("src");
        if (Files.isDirectory(src)) hashTree(md, src);
        return hex(md.digest());
    }

    static void hashTree(MessageDigest md, Path dir) throws IOException {
        List<Path> files;
        try (Stream<Path> s = Files.walk(dir)) { files = s.filter(Files::isRegularFile).sorted().collect(Collectors.toList()); }
        for (Path p : files) {
            md.update((dir.relativize(p).toString().replace('\\', '/') + "\n").getBytes(StandardCharsets.UTF_8));
            md.update(Files.readAllBytes(p));
        }
    }

    // -------------------------------------------------------------------------------------------- makepatches

    static void makePatches() throws Exception {
        Path pristine = gen.resolve("pristine/g3"), src = gen.resolve("src/g3");
        if (!Files.isDirectory(pristine) || !Files.isDirectory(src)) throw new Failure("run setupGame first");
        Path pdir = patches.resolve("g3");
        deleteTree(pdir);
        Files.createDirectories(pdir);
        Set<String> names = new TreeSet<>();
        for (Path d : new Path[] {pristine, src}) {
            try (Stream<Path> s = Files.list(d)) { s.forEach(p -> names.add(p.getFileName().toString())); }
        }
        int files = 0, hunks = 0, removed = 0, added = 0;
        for (String n : names) {
            if (!Files.exists(src.resolve(n))) throw new Failure("generated source " + n + " was deleted; deleting decompiled classes is not supported");
            if (!Files.exists(pristine.resolve(n))) throw new Failure(n + " is not a decompiled class (new classes go into game/src/port/java)");
            List<String> d = Patcher.diff(Patcher.readLines(pristine.resolve(n)), Patcher.readLines(src.resolve(n)), "g3/" + n);
            if (d.isEmpty()) continue;
            Patcher.writeLines(pdir.resolve(n + ".patch"), d);
            files++;
            for (String l : d) {
                if (l.startsWith("@@")) hunks++;
                else if (l.startsWith("-") && !l.startsWith("---")) removed++;
                else if (l.startsWith("+") && !l.startsWith("+++")) added++;
            }
        }
        // round trip: patches applied to pristine must reproduce the edited tree
        for (String n : names) {
            Path p = pdir.resolve(n + ".patch");
            List<String> base = Patcher.readLines(pristine.resolve(n));
            List<String> res = Files.exists(p) ? Patcher.apply(base, Patcher.readLines(p), n) : base;
            if (!res.equals(Patcher.readLines(src.resolve(n)))) throw new Failure("internal error: patch round trip differs for " + n);
        }
        writeStamp(inputsHash(cfg.getProperty("jar.sha256"), pl.tool("tiny-remapper"), pl.tool("vineflower")));
        System.out.println("makePatches: " + files + " patch files, " + hunks + " hunks, " + removed + " removed lines, " + added + " added lines");
    }

    static void record() throws Exception {
        Path pristine = gen.resolve("pristine");
        if (!Files.isDirectory(pristine)) throw new Failure("no game/gen/pristine");
        StringBuilder sb = new StringBuilder("# SHA-256 of the raw decompile output (remap + Vineflower, before patches). setupGame fails if any differs.\n");
        List<Path> files;
        try (Stream<Path> s = Files.walk(pristine)) { files = s.filter(Files::isRegularFile).sorted().collect(Collectors.toList()); }
        for (Path p : files)
            sb.append(sha256(p)).append("  ").append(pristine.relativize(p).toString().replace('\\', '/')).append('\n');
        Files.writeString(patches.resolve("decompile.sha256"), sb.toString());
    }

}
